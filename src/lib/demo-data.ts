const d = (daysAgo: number, h = 8) =>
  new Date(Date.now() - daysAgo * 86400000 - h * 3600000).toISOString();

function ev(id: string, daysAgo: number, actor: string, title: string,
  kind: TimelineEvent["kind"], description?: string): TimelineEvent {
  return { id, timestamp: d(daysAgo), actor, title, description, kind };
}
function comment(id: string, daysAgo: number, author: string, body: string): IncidentComment {
  return { id, author, timestamp: d(daysAgo), body };
}
function evItem(id: string, filename: string, kind: EvidenceItem["kind"],
  uploadedBy: string, daysAgo: number): EvidenceItem {
  return {
    id, filename, kind, uploadedBy, uploadedAt: d(daysAgo),
    sizeLabel: ["48 KB","1.2 MB","350 KB","780 KB","2.1 MB","90 KB"][Math.abs(id.charCodeAt(3) % 6)],
    hash: "sha256:3a7bd3e2360a3d29eea436fcfb7e44c735d117c42d1c1835420b6b9942dd4f1b",
  };
}

